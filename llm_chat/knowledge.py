def search(text, k=2):
    """질문과 관련된 메모를 최대 k개 찾는다."""
    low = str(text).lower()
    flat = low.replace(" ", "")
    scored = []
    for i, (keys, note) in enumerate(NOTES):
        score = sum(len(key) for key in keys if key in low or key.replace(" ", "") in flat)
        if score:
            scored.append((-score, i, note))
    return [note for _, _, note in sorted(scored)[:k]]
